const assert = require('node:assert/strict');
module.exports = async (browser, base) => {
  const contexts = await Promise.all([0, 1, 2].map(() => browser.newContext({ viewport: { width: 1280, height: 800 } })));
  const [gm, player, manual] = await Promise.all(contexts.map(c => c.newPage()));
  const errors = []; for (const page of [gm, player, manual]) page.on('pageerror', e => errors.push(e.message));
  const connected = page => page.getByLabel('Room connection status').filter({ hasText: 'ROOM CONNECTED' }).waitFor({ state: 'attached' });
  let creations = 0, joins = 0, release;
  gm.on('request', r => { if (r.method() === 'POST' && new URL(r.url()).pathname === '/api/rooms') creations++; });
  player.on('request', r => { if (r.method() === 'POST' && r.url().endsWith('/join')) joins++; });
  try {
    await gm.goto(base); await gm.getByRole('button', { name: 'Online room', exact: true }).click();
    await gm.getByRole('button', { name: 'Create room', exact: true }).click();
    await gm.getByRole('alert').filter({ hasText: 'Enter a name or nickname to create the room.' }).waitFor();
    assert.equal(creations, 0); assert.equal(await gm.getByLabel('Your player name', { exact: true }).evaluate(e => document.activeElement === e), true);
    await gm.getByLabel('Your player name', { exact: true }).fill('Guide');
    await gm.getByLabel('Your player name', { exact: true }).press('Enter'); await connected(gm);
    assert.equal(creations, 1);
    const invitation = await gm.getByLabel('Player invitation', { exact: true }).inputValue();
    await player.goto(invitation);
    await player.getByRole('button', { name: 'Join room', exact: true }).waitFor();
    assert.equal(await player.getByRole('button', { name: 'Create room', exact: true }).count(), 0, 'Invitation entry focuses on joining');
    assert.equal(await player.getByRole('button', { name: 'Join room', exact: true }).isEnabled(), true, 'Blank name no longer silently disables joining');
    await player.getByRole('button', { name: 'Join room', exact: true }).click();
    await player.getByRole('alert').filter({ hasText: 'Enter a name or nickname to join the room.' }).waitFor();
    assert.equal(joins, 0);
    const name = player.getByLabel('Your player name', { exact: true });
    assert.equal(await name.getAttribute('aria-invalid'), 'true');
    assert.equal(await name.evaluate(e => document.activeElement === e), true);
    await name.fill('   '); await name.press('Enter'); assert.equal(joins, 0);
    await player.setViewportSize({ width: 390, height: 780 });
    await player.screenshot({ path: '.test-artifacts/join-name-required.png' });
    await name.fill('  New Player  '); assert.equal(await name.getAttribute('aria-invalid'), 'false');
    await player.route('**/join', async route => { const response = await route.fetch(); await new Promise(r => release = r); await route.fulfill({ response }); });
    await name.press('Enter');
    await player.getByRole('button', { name: 'Joining…', exact: true }).waitFor();
    assert.equal(await player.getByRole('button', { name: 'Joining…', exact: true }).isEnabled(), false);
    await name.press('Enter'); assert.equal(joins, 1, 'Repeated Enter cannot submit a second request while joining');
    const deadline = Date.now() + 5000;
    while (!release && Date.now() < deadline) await new Promise(r => setTimeout(r, 10));
    assert(release, 'The submitted join must reach the server');
    release(); await connected(player);
    assert.match(await player.getByRole('region', { name: 'Online room controls' }).innerText(), /New Player · Player/);
    await manual.goto(base); await manual.getByRole('button', { name: 'Online room', exact: true }).click();
    await manual.getByLabel('Your player name', { exact: true }).fill('Guest');
    await manual.getByRole('button', { name: 'Join room', exact: true }).click();
    await manual.getByRole('alert').filter({ hasText: 'Paste an invitation link to join.' }).waitFor();
    assert.equal(await manual.getByLabel('Room invitation link', { exact: true }).evaluate(e => document.activeElement === e), true);
    await manual.getByLabel('Room invitation link', { exact: true }).fill(`${base}/#room=invalid&invite=x`);
    await manual.getByLabel('Room invitation link', { exact: true }).press('Enter');
    await manual.getByRole('alert').filter({ hasText: 'Paste a complete room invitation link.' }).waitFor();
    assert.deepEqual(errors, []);
    console.log('PASS: invitation entry, visible/focused name and link validation, whitespace rejection, keyboard join/create, busy feedback and single-submit protection');
  } finally { if (release) release(); await Promise.all(contexts.map(c => c.close())); }
};
