const assert = require("node:assert/strict");
exports.testUI = async (page) => {
  await page.reload();
  await page.locator(".loading-cover").waitFor({ state: "hidden" });
  const mood = () => page.getByRole("button", { name: "Table mood", exact: true }).click();
  const openPresets = (kind) => page.getByText(`${kind} presets`, { exact: true }).click();
  const save = async (kind, name) => {
    await page.getByRole("textbox", { name: `${kind} preset name`, exact: true }).fill(name);
    await page.locator(".preset-control").filter({ has: page.getByText(`${kind} presets`, { exact: true }) }).getByRole("button", { name: "Save", exact: true }).click();
  };
  const toggle = async (name, on) => {
    await page.getByRole("button", { name: "Widgets", exact: true }).click();
    await page.getByRole("checkbox", { name: `${name} widget`, exact: true }).setChecked(on);
    await page.getByRole("button", { name: "Widgets", exact: true }).click();
    if (on) { const title = name === "3D dice" ? "Dice" : name; if (!(await page.getByRole("region", { name: `${title} controls`, exact: true }).count())) await page.getByRole("button", { name: `Open ${title} widget`, exact: true }).click(); }
  };
  const hex = async (label, value) => {
    await page.getByRole("textbox", { name: `${label} hex`, exact: true }).fill(value);
    await page.keyboard.press("Enter");
  };
  const slider = (label, value) => page.getByRole("slider", { name: label, exact: true }).fill(String(value));
  await mood(); await openPresets("Theme");
  await slider("Table hue", 230); await slider("Table saturation", 38); await slider("Table lightness", 9);
  await page.getByRole("button", { name: "Campfire", exact: true }).click();
  await hex("Effect color", "#5599ff"); await slider("Animation strength", 210); await slider("Animation spread", 150);
  await save("Theme", "Night blue");
  await slider("Table saturation", 44);
  await page.getByRole("button", { name: "Update", exact: true }).click();
  await page.getByRole("alertdialog").getByRole("button", { name: "Overwrite", exact: true }).click();
  assert.equal(await page.getByRole("combobox", { name: "Theme preset", exact: true }).locator("option").count(), 3);
  await page.screenshot({ path: ".test-artifacts/theme-presets.png" });
  await require("./preset-actions.cjs").basicMood(page);
  await require("./preset-actions.cjs").selectPreset(page, "Theme", "Night blue");
  assert.equal(await page.getByRole("slider", { name: "Table saturation" }).inputValue(), "44");
  assert.equal(await page.getByLabel("Effect color", { exact: true }).inputValue(), "#5599ff");
  await slider("Table saturation", 2);
  await require("./preset-actions.cjs").selectPreset(page, "Theme", "Night blue");
  assert.equal(await page.getByRole("slider", { name: "Table saturation" }).inputValue(), "44");
  await mood();
  await toggle("3D dice", true);
  await page.getByRole("button", { name: "Clear dice selection", exact: true }).click();
  await page.getByText("Dice colors", { exact: true }).click();
  await page.getByRole("textbox", { name: "Dice group name", exact: true }).fill("Attack");
  await hex("Dice color", "#ee2244"); await hex("Numeral color", "#ffffff");
  await page.getByRole("button", { name: "Add d6", exact: true }).click();
  await page.getByRole("button", { name: "+ Add color group", exact: true }).click();
  await page.getByRole("textbox", { name: "Dice group name", exact: true }).fill("Damage");
  await hex("Dice color", "#2244ee"); await hex("Numeral color", "#ffee00");
  await page.getByRole("button", { name: "Add d6", exact: true }).click();
  await page.getByRole("button", { name: "Add d6", exact: true }).click();
  assert.equal(await page.locator(".dice-pool > span").textContent(), "3d6");
  await page.getByRole("button", { name: "Use dice group Attack", exact: true }).click();
  assert.equal(await page.locator(".die-choice").filter({ has: page.getByRole("button", { name: "Add d6", exact: true }) }).locator("b").textContent(), "1");
  await openPresets("Dice"); await save("Dice", "Attack & damage");
  await page.getByText("Dice colors", { exact: true }).click(); await openPresets("Dice");
  await page.getByRole("button", { name: "Roll dice", exact: true }).click();
  await page.waitForFunction(() => document.querySelector(".dice-result strong"));
  assert.equal(await page.locator(".dice-result .group-result").count(), 2);
  const resultGroups = await page.locator(".dice-result .group-result").allTextContents();
  assert.ok(resultGroups[0].startsWith("Attack") && resultGroups[1].startsWith("Damage"));
  const dots = await page.locator(".dice-result .group-result i").evaluateAll((els) => els.map((el) => getComputedStyle(el).backgroundColor));
  assert.deepEqual(dots, ["rgb(238, 34, 68)", "rgb(34, 68, 238)"]);
  await page.screenshot({ path: ".test-artifacts/dice-groups.png" });
  await page.getByRole("button", { name: "Use dice group Damage", exact: true }).click();
  await page.getByText("Dice colors", { exact: true }).click();
  await hex("Dice color", "#22ee44");
  assert.deepEqual(await page.locator(".roll-history .group-result i").evaluateAll((els) => els.map((el) => getComputedStyle(el).backgroundColor)), dots);
  await page.getByRole("button", { name: "Remove group", exact: true }).click();
  assert.equal(await page.locator(".dice-groups").count(), 0);
  await openPresets("Dice");
  await require("./preset-actions.cjs").selectPreset(page, "Dice", "Attack & damage");
  assert.equal(await page.locator(".dice-groups button").count(), 2);
  await toggle("Grid & measure", true);
  await openPresets("Grid");
  await slider("Grid square size", 123); await slider("Grid rotation", 27);
  await page.getByRole("textbox", { name: "Scale unit name", exact: true }).fill("paces");
  await save("Grid", "Paces");
  await page.reload();
  await page.locator(".loading-cover").waitFor({ state: "hidden" });
  await mood(); await openPresets("Theme");
  await require("./preset-actions.cjs").selectPreset(page, "Theme", "Night blue");
  assert.equal(await page.getByRole("slider", { name: "Table hue", exact: true }).inputValue(), "230");
  assert.equal(await page.getByRole("slider", { name: "Table lightness", exact: true }).inputValue(), "9");
  assert.equal(await page.getByRole("slider", { name: "Animation strength", exact: true }).inputValue(), "210");
  await mood(); await toggle("3D dice", true); await openPresets("Dice");
  await require("./preset-actions.cjs").selectPreset(page, "Dice", "Attack & damage");
  assert.equal(await page.locator(".dice-pool > span").textContent(), "3d6");
  await page.getByRole("button", { name: "Use dice group Damage", exact: true }).click();
  await page.getByText("Dice colors", { exact: true }).click();
  assert.equal(await page.getByLabel("Dice color", { exact: true }).inputValue(), "#2244ee");
  assert.equal(await page.getByLabel("Numeral color", { exact: true }).inputValue(), "#ffee00");
  await page.getByRole("button", { name: "Delete dice preset", exact: true }).click();
  assert.equal(await page.getByRole("combobox", { name: "Dice preset", exact: true }).isDisabled(), false);
  await toggle("Grid & measure", true); await openPresets("Grid");
  await require("./preset-actions.cjs").selectPreset(page, "Grid", "Paces");
  assert.equal(await page.getByRole("slider", { name: "Grid rotation", exact: true }).inputValue(), "27");
  assert.equal(await page.getByRole("slider", { name: "Grid square size", exact: true }).inputValue(), "123");
  assert.equal(await page.getByRole("textbox", { name: "Scale unit name", exact: true }).inputValue(), "paces");
  // Compact windows keep panels scrollable without widening the page.
  await page.setViewportSize({ width: 720, height: 560 });
  await page.getByRole("button", { name: "Open Dice widget", exact: true }).click();
  assert.ok(await page.locator(".widget-panel").evaluate((el) => el.scrollHeight > el.clientHeight));
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({ path: ".test-artifacts/presets-compact.png" });
  await page.setViewportSize({ width: 1440, height: 900 });
  console.log("PASS: dice color groups, per-group selections, identified results/history, named preset save/update/apply/delete, full theme/grid restore and persistence across reloads");
};
